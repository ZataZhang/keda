def test_create_draft_pr_injects_contract_teaching_into_agent_prompt(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """agent 模式下发布契约参考文本必须进入生成 prompt（教学注入）。"""
    from backend.core.shared.models.agent_runner import (
        AppConfig,
        CommandResult,
        GeneratedContentConfig,
        GeneratedContentTargetConfig,
    )
    from backend.core.use_cases import agent_runner_publish as publish_module
    from backend.core.use_cases.agent_runner_publish import create_draft_pr
    from tests.conftest import FakeGitHubClient

    skill_path = _write_skill(tmp_path, with_reference=True)
    contract_text = load_prd_publish_contract(skill_path)
    assert contract_text is not None
    monkeypatch.setattr(publish_module, "load_prd_publish_contract", lambda: contract_text)

    captured_prompts: list[str] = []

    class RecordingGenerator:
        def generate(self, agent_name: str, prompt: str, *, cwd, timeout=None):
            captured_prompts.append(prompt)
            return CommandResult(
                command=("fake",),
                return_code=0,
                stdout=(
                    "[Agent] Test Feature\n\nCloses #42\n\n"
                    "- PRD: tasks/pending/20260928-feature.md\n"
                    f"{MERGE_ACCEPTANCE_MARKER_TEXT}\n"
                ),
                stderr="",
            )

    app_config = AppConfig(
        generated_content=GeneratedContentConfig(
            enabled=True,
            draft_pr=GeneratedContentTargetConfig(
                enabled=True,
                mode="agent",
                output="markdown",
                prompt="Generate a draft PR body.",
            ),
        ),
    )
    issue = _publish_issue(42, _ISSUE_BODY_WITH_PRD)
    fake_client = FakeGitHubClient()
    create_draft_pr(
        issue,
        Path("."),
        app_config,
        fake_client,
        _fake_runner_for("issue-42"),
        content_generator=RecordingGenerator(),
    )
    assert captured_prompts, "agent generator should have been invoked"
    assert "PR-Native Acceptance contract" in captured_prompts[0]
    assert MERGE_ACCEPTANCE_MARKER_TEXT in captured_prompts[0]
    # 教学注入后原 config prompt 仍保留在 prompt 尾部。
    assert captured_prompts[0].endswith("Generate a draft PR body.")
    # 合规正文不应被追加标注块。
    pr_calls = [c for c in fake_client.calls if c["method"] == "create_draft_pr"]
    assert has_contract_annotation(pr_calls[0]["body"]) is False


