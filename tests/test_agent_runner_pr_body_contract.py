def test_create_draft_pr_appends_contract_annotation_for_fallback_body() -> None:
    """生成被禁用时 fallback body 对 PRD 交付必须被标注为契约不合规。"""
    from pathlib import Path

    from backend.core.shared.models.agent_runner import AppConfig
    from backend.core.use_cases.agent_runner_publish import create_draft_pr
    from tests.conftest import FakeGitHubClient

    issue = _publish_issue(42, _ISSUE_BODY_WITH_PRD)
    fake_client = FakeGitHubClient()
    branch, pr_url = create_draft_pr(
        issue,
        Path("."),
        AppConfig(),
        fake_client,
        _fake_runner_for("issue-42"),
    )
    assert pr_url
    pr_calls = [c for c in fake_client.calls if c["method"] == "create_draft_pr"]
    assert len(pr_calls) == 1
    body = pr_calls[0]["body"]
    assert body.startswith("Closes #42")
    assert has_contract_annotation(body)
    assert parse_contract_annotation(body) == ["prd-link", "merge-acceptance"]
    assert "autopilot merge queue will refuse" in body


