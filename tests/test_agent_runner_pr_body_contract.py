"""Tests for the PR body contract alignment layer (prd skill publish mode).

覆盖 :mod:`agent_runner_pr_body_contract` 的三段能力：skill 发布契约参考的
加载与 prompt 教学、发布端软门（锚点校验 + 不合规标注）、以及合并队列硬门
消费的 marker 解析。"""

from __future__ import annotations

from pathlib import Path

import pytest

from backend.core.use_cases.agent_runner_pr_body_contract import (
    MERGE_ACCEPTANCE_MARKER_TEXT,
    build_contract_annotation_block,
    build_contract_prompt_prefix,
    find_pr_body_contract_violations,
    has_contract_annotation,
    load_prd_publish_contract,
    parse_contract_annotation,
)

_ISSUE_BODY_WITH_PRD = "PRD path: `tasks/pending/20260928-feature.md`\n\nSome description."
_ISSUE_BODY_WITHOUT_PRD = "Just a bug report with no PRD anchor."
_COMPLIANT_BODY = "\n".join(
    [
        "Closes #42",
        "",
        "- PRD: tasks/pending/20260928-feature.md",
        "Merging this PR constitutes acceptance and authorizes archival.",
        MERGE_ACCEPTANCE_MARKER_TEXT,
        "",
    ]
)


def _write_skill(tmp_path: Path, *, with_reference: bool) -> Path:
    """在 tmp_path 下伪造一份最小 prd skill 安装，返回 SKILL.md 路径。"""
    skill_dir = tmp_path / "skills" / "prd"
    skill_dir.mkdir(parents=True)
    skill_path = skill_dir / "SKILL.md"
    skill_path.write_text("---\nname: prd\n---\n# PRD Generator\n", encoding="utf-8")
    if with_reference:
        references_dir = skill_dir / "references"
        references_dir.mkdir()
        (references_dir / "pr-evidence-and-merge-acceptance.md").write_text(
            "# PR Evidence And Merge Acceptance\n1. The PR body uniquely names the PRD.\n",
            encoding="utf-8",
        )
    return skill_path


def test_load_prd_publish_contract_reads_reference(tmp_path: Path) -> None:
    """契约参考文本应从 SKILL.md 同级 references/ 目录读取。"""
    skill_path = _write_skill(tmp_path, with_reference=True)
    contract_text = load_prd_publish_contract(skill_path)
    assert contract_text is not None
    assert "PR-Native" in contract_text or "PR body" in contract_text


def test_load_prd_publish_contract_returns_none_without_reference(tmp_path: Path) -> None:
    """skill 存在但参考文档缺失（旧版安装）时应安全返回 None。"""
    skill_path = _write_skill(tmp_path, with_reference=False)
    assert load_prd_publish_contract(skill_path) is None


def test_load_prd_publish_contract_returns_none_when_skill_missing(tmp_path: Path) -> None:
    """skill 完全不可达时应安全返回 None 而不是抛错。"""
    assert load_prd_publish_contract(tmp_path / "nonexistent" / "SKILL.md") is None


def test_contract_prompt_prefix_contains_teaching_anchors(tmp_path: Path) -> None:
    """prompt 教学段必须包含 PRD 行、merge-acceptance marker 与参考文本。"""
    skill_path = _write_skill(tmp_path, with_reference=True)
    contract_text = load_prd_publish_contract(skill_path)
    assert contract_text is not None
    prefix = build_contract_prompt_prefix(contract_text)
    assert "- PRD: <relative prd path>" in prefix
    assert MERGE_ACCEPTANCE_MARKER_TEXT in prefix
    assert "Never pre-tick" in prefix
    assert "pr-evidence-and-merge-acceptance" in prefix or "PR body" in contract_text


def test_find_violations_flags_both_missing_anchors() -> None:
    """fallback body（只有 Closes）对 PRD 交付应同时缺 prd-link 与声明。"""
    violations = find_pr_body_contract_violations(
        "Closes #42\n\nGenerated by issue-agent-runner.\n", _ISSUE_BODY_WITH_PRD
    )
    assert violations == ["prd-link", "merge-acceptance"]


def test_find_violations_empty_for_compliant_body() -> None:
    assert find_pr_body_contract_violations(_COMPLIANT_BODY, _ISSUE_BODY_WITH_PRD) == []


def test_find_violations_skip_issues_without_prd() -> None:
    """无 PRD 锚点的 Issue 不新增契约要求（prd skill 管辖范围之外）。"""
    assert find_pr_body_contract_violations("Closes #7", _ISSUE_BODY_WITHOUT_PRD) == []


def test_annotation_block_roundtrip() -> None:
    """标注块写入的 marker 必须能被合并队列侧的解析函数原样读回。"""
    violations = ["prd-link", "merge-acceptance"]
    block = build_contract_annotation_block(violations)
    assert parse_contract_annotation(block) == violations
    assert has_contract_annotation(block) is True
    assert has_contract_annotation(_COMPLIANT_BODY) is False
    assert parse_contract_annotation(_COMPLIANT_BODY) == []


def test_annotation_block_lists_human_readable_descriptions() -> None:
    block = build_contract_annotation_block(["prd-link"])
    assert "`prd-link`" in block
    assert "pending PRD path" in block


@pytest.mark.parametrize(
    ("marker_line", "expected"),
    [
        ("<!-- iar:pr-contract version=1 missing=prd-link -->", ["prd-link"]),
        (
            "<!--iar:pr-contract version=1 missing=prd-link,merge-acceptance-->",
            ["prd-link", "merge-acceptance"],
        ),
        ("<!-- iar:pr-contract version=1 missing= -->", []),
    ],
)
def test_parse_contract_annotation_marker_variants(marker_line: str, expected: list[str]) -> None:
    assert parse_contract_annotation(marker_line) == expected


