def _draft_pr_app_config(*, mode: str, **target_overrides: str):
    """构造只开启 ``draft_pr`` 生成的 AppConfig，``target_overrides`` 透传给 target 配置。"""
    from backend.core.shared.models.agent_runner import (
        AppConfig,
        GeneratedContentConfig,
        GeneratedContentTargetConfig,
    )

    return AppConfig(
        generated_content=GeneratedContentConfig(
            enabled=True,
            draft_pr=GeneratedContentTargetConfig(enabled=True, mode=mode, **target_overrides),
        )
    )


def _published_pr_call(issue, app_config, *, content_generator=None) -> dict:
    """走一遍 ``create_draft_pr``，返回 FakeGitHubClient 记录下的唯一一次建 PR 调用。"""
    from backend.core.use_cases.agent_runner_publish import create_draft_pr
    from tests.conftest import FakeGitHubClient

    fake_client = FakeGitHubClient()
    create_draft_pr(
        issue,
        Path("."),
        app_config,
        fake_client,
        _fake_runner_for(f"issue-{issue.number}"),
        content_generator=content_generator,
    )
    pr_calls = [c for c in fake_client.calls if c["method"] == "create_draft_pr"]
    assert len(pr_calls) == 1
    return pr_calls[0]


