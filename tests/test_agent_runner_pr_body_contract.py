def test_merge_queue_skips_prs_with_contract_annotation(tmp_path) -> None:
    """发布端标注过 ``iar:pr-contract`` 的 PR 必须被合并队列拒绝。"""
    from backend.core.shared.models.agent_runner import PullRequestContext
    from backend.core.use_cases.agent_runner_merge_queue import _process_one
    from tests.conftest import FakeGitHubClient, FakeProcessRunner
    from tests.test_agent_runner_merge_queue import _make_config, _make_issue

    github = FakeGitHubClient()
    pr_context = PullRequestContext(
        pr_url="https://github.com/example/repo/pull/70",
        branch="issue-70",
        head_sha="abc1234",
        base_sha="base1234",
        mergeable=True,
        checks_state="SUCCESS",
        number=70,
        body="Closes #70\n\n" + build_contract_annotation_block(["prd-link"]),
    )
    github.set_pr_context("issue-70", pr_context)
    github._issue_comments[70] = ["PR Branch: `issue-70`"]

    outcome = _process_one(
        repo_path=tmp_path,
        config=_make_config(require_verifier_pass=False, auto_sign_off=False),
        issue=_make_issue(number=70, labels=("agent/review",)),
        github_client=github,
        process_runner=FakeProcessRunner(),
        supervisor_agent="auto",
    )
    assert outcome.action == "skipped_pr_contract_missing"
    merge_calls = [c for c in github.calls if c.get("method") == "merge_pull_request"]
    assert merge_calls == []
    # 硬门在 rebase / 签核之前生效，不产生 body 变更。
    body_calls = [c for c in github.calls if c.get("method") == "update_pull_request_body"]
    assert body_calls == []


